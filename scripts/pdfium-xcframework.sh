#!/usr/bin/env bash
# Usage: scripts/pdfium-xcframework.sh [--embedpdf]
# Packs every slice found in dist/slices/*/libpdfium.a into dist/PDFium.xcframework and zips it to
# dist/PDFium.xcframework.zip (ditto --keepParent, so the zip has PDFium.xcframework/ at its top level).
# Headers: Headers/module.modulemap at the root, and in Headers/PDFium/ every public/fpdf*.h and public/epdf_*.h
# of the checkout plus a generated PDFium.h umbrella header. The subfolder keeps the umbrella header's folder free
# of other frameworks' headers when SwiftPM merges every static XCFramework's Headers/ into one include folder.
# A header that the engine binding needs but upstream no longer ships (renamed or removed) stops the script with
# its name; a stock build refuses a tree that carries epdf_*.h headers.
# Environment (optional): WORK_DIR, DIST_DIR, PDFIUM_DIR (default $WORK_DIR/pdfium).
# Exit codes: 0 ok, 2 usage or missing tool, 3 header problem or no slice, 4 xcodebuild or header compile failure.
set -euo pipefail
# shellcheck source=common.sh
. "$(dirname "${BASH_SOURCE[0]}")/common.sh"

MODE=stock
case "${1:-}" in
  '') ;;
  --embedpdf) MODE=embedpdf ;;
  *) die 2 "usage: $SCRIPT_NAME [--embedpdf]" ;;
esac
[ "$#" -le 1 ] || die 2 "usage: $SCRIPT_NAME [--embedpdf]"

PDFIUM_DIR="${PDFIUM_DIR:-$WORK_DIR/pdfium}"
PUBLIC="$PDFIUM_DIR/public"
STAGING="$DIST_DIR/headers-staging"
XCF="$DIST_DIR/PDFium.xcframework"
ZIP="$DIST_DIR/PDFium.xcframework.zip"
require_cmd xcodebuild ditto plutil clang
# Remove the previous output first, so a run that stops on a header problem never leaves an old framework behind.
rm -rf "$XCF" "$ZIP"

# Headers the engine binding relies on. If upstream renames one, extend this list only after reading public/.
STOCK_HEADERS="fpdfview.h fpdf_annot.h fpdf_attachment.h fpdf_catalog.h fpdf_dataavail.h fpdf_doc.h fpdf_edit.h fpdf_ext.h fpdf_flatten.h fpdf_formfill.h fpdf_fwlevent.h fpdf_javascript.h fpdf_ppo.h fpdf_progressive.h fpdf_save.h fpdf_searchex.h fpdf_signature.h fpdf_structtree.h fpdf_sysfontinfo.h fpdf_text.h fpdf_thumbnail.h fpdf_transformpage.h"
EPDF_HEADERS="epdf_action.h epdf_annot.h epdf_attachment.h epdf_capture.h epdf_catalog.h epdf_digest.h epdf_doc.h epdf_edit.h epdf_flatten.h epdf_font.h epdf_form.h epdf_layer.h epdf_measure.h epdf_named_pages.h epdf_pieceinfo.h epdf_png.h epdf_progressive.h epdf_redact.h epdf_save.h epdf_signature.h epdf_text.h epdf_view.h"
EPDF_EXTRA_FPDF_HEADERS=""

[ -d "$PUBLIC" ] || die 3 "no public/ directory at $PUBLIC (run scripts/pdfium-checkout.sh first)"

# Required headers present?
required="$STOCK_HEADERS"
if [ "$MODE" = embedpdf ]; then
  required="$required $EPDF_HEADERS $EPDF_EXTRA_FPDF_HEADERS"
fi
missing=""
for h in $required; do
  [ -f "$PUBLIC/$h" ] || missing="$missing $h"
done
if [ -n "$missing" ]; then
  die 3 "required header(s) missing from $PUBLIC:$missing. Upstream may have renamed or removed them; read public/ in the checkout and update the header lists in scripts/pdfium-xcframework.sh."
fi

# A stock build must not ship EmbedPDF headers.
if [ "$MODE" = stock ]; then
  extra="$(cd "$PUBLIC" && ls epdf_*.h 2>/dev/null | tr '\n' ' ' || true)"
  [ -z "$extra" ] || die 3 "stock build but the tree has EmbedPDF header(s): $extra"
fi

# Slices.
slices=()
for dir in "$DIST_DIR"/slices/*/; do
  [ -f "${dir}libpdfium.a" ] && slices+=("${dir%/}")
done
[ "${#slices[@]}" -gt 0 ] || die 3 "no slice found: expected $DIST_DIR/slices/<slice>/libpdfium.a (run scripts/pdfium-build.sh first)"

# Stage headers and generate the umbrella header and module map.
rm -rf "$STAGING"
mkdir -p "$STAGING/PDFium"
others=""
for path in "$PUBLIC"/fpdf*.h "$PUBLIC"/epdf_*.h; do
  [ -f "$path" ] || continue
  h="$(basename "$path")"
  cp "$path" "$STAGING/PDFium/$h"
  case " $STOCK_HEADERS $EPDF_HEADERS $EPDF_EXTRA_FPDF_HEADERS " in
    *" $h "*) ;;
    *) log "note: header not in the known list, added to the umbrella anyway: $h" ;;
  esac
  [ "$h" = "fpdfview.h" ] || others="$others $h"
done
{
  echo "// Generated by scripts/pdfium-xcframework.sh. Do not edit."
  echo "#ifndef PDFIUM_UMBRELLA_H_"
  echo "#define PDFIUM_UMBRELLA_H_"
  echo '#include "fpdfview.h"'
  for h in $(echo "$others" | tr ' ' '\n' | LC_ALL=C sort); do
    echo "#include \"$h\""
  done
  echo "#endif  // PDFIUM_UMBRELLA_H_"
} >"$STAGING/PDFium/PDFium.h"
cat >"$STAGING/module.modulemap" <<'EOF'
module PDFium {
  umbrella header "PDFium/PDFium.h"
  export *
  link "c++"
}
EOF

# The umbrella header must compile as C, as C++ and as a clang module that covers every staged header.
log "compiling the umbrella header as C, C++ and a module"
clang -fsyntax-only -Wno-strict-prototypes -x c -I "$STAGING" "$STAGING/PDFium/PDFium.h" || die 4 "PDFium.h does not compile as C"
clang -fsyntax-only -x c++ -I "$STAGING" "$STAGING/PDFium/PDFium.h" || die 4 "PDFium.h does not compile as C++"
modcheck="$(mktemp -d "${TMPDIR:-/tmp}/pdfium-modcheck.XXXXXX")"
printf '@import PDFium;\n' >"$modcheck/check.m"
clang -fsyntax-only -fmodules -fmodules-cache-path="$modcheck/cache" -Wno-strict-prototypes -Werror=incomplete-umbrella \
  -I "$STAGING" "$modcheck/check.m" \
  || { rm -rf "$modcheck"; die 4 "the PDFium module map does not import"; }
rm -rf "$modcheck"

# Create and zip the XCFramework.
rm -rf "$XCF" "$ZIP"
args=()
for dir in "${slices[@]}"; do
  args+=(-library "$dir/libpdfium.a" -headers "$STAGING")
done
log "xcodebuild -create-xcframework with ${#slices[@]} slice(s)"
xcodebuild -create-xcframework "${args[@]}" -output "$XCF" >/dev/null || die 4 "xcodebuild -create-xcframework failed"
plutil -lint "$XCF/Info.plist" >/dev/null || die 4 "XCFramework Info.plist is not valid"
count="$(plutil -extract AvailableLibraries raw -o - "$XCF/Info.plist")"
[ "$count" = "${#slices[@]}" ] || die 4 "XCFramework lists $count libraries, expected ${#slices[@]}"
ditto -c -k --keepParent "$XCF" "$ZIP"
log "wrote $ZIP ($(wc -c <"$ZIP" | tr -d ' ') bytes, $MODE, ${#slices[@]} slice(s))"
